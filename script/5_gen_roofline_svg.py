TABLE_ROW_RE = re.compile(r"^\|(.+)\|\s*$")


# ---------------------------------------------------------------------------
# Parse doc/dtln/roofline_log.txt (script/4_roofline_report.py's output).
# ---------------------------------------------------------------------------


def parse_cell(s):
    s = s.strip()
    return s


def parse_table(lines, start_idx):
    """lines[start_idx] is the table's header row ('| col | col | ... |').
    Returns (header_cells, data_rows, next_idx) -- next_idx is the line
    index right after the last row of this table."""
    header = [parse_cell(c) for c in lines[start_idx].strip().strip("|").split("|")]
    i = start_idx + 1
    if i < len(lines) and set(lines[i].strip()) <= set("|-: "):
        i += 1  # skip the '|---|---|' separator row
    rows = []
    while i < len(lines) and TABLE_ROW_RE.match(lines[i]):
        cells = [parse_cell(c) for c in lines[i].strip().strip("|").split("|")]
        rows.append(dict(zip(header, cells)))
        i += 1
    return rows, i


def clean_number(s):
    """'0.05%' -> 0.05, '1,234.56' -> 1234.56, '`FULLY_CONNECTED`' -> FULLY_CONNECTED (non-numeric passthrough)."""
    s = s.strip().strip("`")
    t = s.replace(",", "").rstrip("%")
    try:
        return float(t)
    except ValueError:
        return s


def parse_report(log_path):
    with open(log_path) as f:
        lines = f.read().splitlines()

    meta = {}
    m = re.search(r"^Model: (\S+)$", "\n".join(lines), re.MULTILINE)
    if m:
        meta["model_name"] = os.path.splitext(os.path.basename(m.group(1)))[0]
    m = re.search(r"peak BW ([\d.]+) GB/s", "\n".join(lines))
    if m:
        meta["peak_bw_gbps"] = float(m.group(1))
    m = re.search(r"idealized peak compute ([\d.]+) GFLOP/s", "\n".join(lines))
    if m:
        meta["peak_compute_gflops"] = float(m.group(1))
    m = re.search(r"ridge point ([\d.]+) FLOP/byte", "\n".join(lines))
    if m:
        meta["ridge_point"] = float(m.group(1))
    m = re.search(r"Empirical compute-roof ceiling: ([\d.]+) GFLOP/s", "\n".join(lines))
    if m:
        meta["ceiling_gflops"] = float(m.group(1))
    m = re.search(r"Empirical fc_bottleneck warm-cache ceiling: ([\d.]+) GFLOP/s", "\n".join(lines))
    if m:
        meta["fc_warm_ceiling_gflops"] = float(m.group(1))
    m = re.search(r"Empirical cold-cache ceiling: ([\d.]+) GFLOP/s", "\n".join(lines))
    if m:
        meta["cold_ceiling_gflops"] = float(m.group(1))

    ai_rows, perf_rows = [], []
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("### Arithmetic intensity"):
            j = i + 1
            while j < len(lines) and not lines[j].startswith("|"):
                j += 1
            ai_rows, i = parse_table(lines, j)
            continue
        if line.startswith("### Achieved performance"):
            j = i + 1
            while j < len(lines) and not lines[j].startswith("|"):
                j += 1
            perf_rows, i = parse_table(lines, j)
            continue
        i += 1

    if not meta or not ai_rows or not perf_rows:
        sys.exit(
            f"error: couldn't find expected sections in {log_path} -- "
            "was it generated by script/4_roofline_report.py?"
        )
    return meta, ai_rows, perf_rows


def build_points(ai_rows, perf_rows):
    """Join the two tables on (op, call) -> [(op, call, variant, ai, gflops), ...]."""
    ai_by_key = {}
    for row in ai_rows:
        key = (row["op"].strip("`"), row["call"])
        ai = clean_number(row["AI (FLOP/byte)"].split()[0])  # "2.00 (memory-bound)" -> 2.00
        ai_by_key[key] = ai

    points = []
    for row in perf_rows:
        key = (row["op"].strip("`"), row["call"])
        if key not in ai_by_key:
            continue  # e.g. LOGISTIC -- no FLOP model, not plottable
        p_mflops = clean_number(row["P (MFLOP/s)"])
        if not isinstance(p_mflops, float):
            continue  # "n/a (no FLOP model for this op)"
        points.append({
            "op": key[0],
            "call": key[1],
            "variant": row["variant"],
            "ai": ai_by_key[key],
            "gflops": p_mflops / 1000.0,
        })
    return points


